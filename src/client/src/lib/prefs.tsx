/**
 * The floating control.
 *
 * Bottom right, above everything, out of the way of the tables and the till.
 * Deliberately not buried in a settings screen: someone squinting at a bright
 * screen at 9pm should be one click from fixing it, not five.
 */
export function AppearanceToggle() {
  const { theme, toggleTheme, setTheme, lang, setLang, t: tr } = usePrefs()
  const [open, setOpen] = useState<'none' | 'theme' | 'lang'>('none')

  return (
    <div className="no-print fixed bottom-5 right-5 z-50 flex flex-col items-end gap-2">
      {open === 'theme' && (
        <div className="panel w-60 p-1.5 shadow-pop">
          <p className="px-2 pb-1 pt-0.5 text-2xs uppercase tracking-wide text-muted">Appearance</p>
          {THEMES.map((th) => (
            <button key={th.id} onClick={() => { setTheme(th.id); setOpen('none') }}
              className={`flex w-full items-center gap-2.5 rounded-xl px-2.5 py-2 text-left ${
                theme === th.id ? 'bg-primary/10' : 'hover:bg-raised'}`}>
              <span className="flex shrink-0 overflow-hidden rounded-md border border-line">
                {th.swatch.map((c) => (
                  <span key={c} className="h-6 w-2.5" style={{ background: c }} />
                ))}
              </span>
              <span className="min-w-0 flex-1">
                <span className={`block text-sm ${
                  theme === th.id ? 'font-medium text-primary' : 'text-body'}`}>{th.label}</span>
                <span className="block text-2xs text-muted">{th.note}</span>
              </span>
              {theme === th.id && <span className="text-primary">&#10003;</span>}
            </button>
          ))}
        </div>
      )}

      {open === 'lang' && (
        <div className="panel w-52 p-1.5 shadow-pop">
          <button onClick={() => { setLang('en'); setOpen('none') }}
            className={`flex w-full items-center justify-between rounded-xl px-3 py-2 text-sm ${
              lang === 'en' ? 'bg-primary/10 font-medium text-primary' : 'text-body hover:bg-raised'}`}>
            English <span className="text-2xs opacity-60">EN</span>
          </button>
          <button onClick={() => { setLang('ur'); setOpen('none') }}
            className={`flex w-full items-center justify-between rounded-xl px-3 py-2 ${
              lang === 'ur' ? 'bg-primary/10 font-medium text-primary' : 'text-body hover:bg-raised'}`}>
            <span className="font-urdu text-base">&#1575;&#1585;&#1583;&#1608;</span>
            <span className="text-2xs opacity-60">UR</span>
          </button>
        </div>
      )}

      <div className="flex items-center gap-2">
        <button onClick={() => setOpen((o) => (o === 'lang' ? 'none' : 'lang'))}
          aria-label={tr('Language')}
          className="flex h-11 items-center rounded-full border-2 border-line bg-card px-4 text-sm
                     font-medium text-body shadow-pop transition-colors hover:border-primary">
          {lang === 'en' ? 'EN' : <span className="font-urdu">&#1575;&#1585;&#1583;&#1608;</span>}
        </button>

        <button onClick={() => setOpen((o) => (o === 'theme' ? 'none' : 'theme'))}
          aria-label="Appearance"
          className="flex h-11 w-11 items-center justify-center rounded-full border-2 border-line
                     bg-card text-body shadow-pop transition-colors hover:border-primary">
          <Palette />
        </button>

        <button onClick={toggleTheme}
          aria-label={theme === 'dark' ? t('Light mode') : t('Dark mode')}
          title={theme === 'dark' ? t('Light mode') : t('Dark mode')}
          className="flex h-11 w-11 items-center justify-center rounded-full bg-brand text-white
                     shadow-pop transition-transform hover:scale-105 active:scale-95">
          {theme === 'dark' ? <Sun /> : <Moon />}
        </button>
      </div>
    </div>
  )
}

